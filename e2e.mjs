import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { existsSync, mkdirSync, readFileSync } from 'node:fs'
import JSZip from 'jszip'
import ExcelJS from 'exceljs'
const source = 'C:/Users/Admin/Downloads/DanhSachHanhTrinh_26-10-2026_01-11-2026.xlsx'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const context = await browser.newContext({ acceptDownloads: true })
const page = await context.newPage()
const prompts = []
page.on('pageerror', error => console.log('PAGE ERROR', error.message))
page.on('dialog', async dialog => { if (dialog.type() === 'prompt') await dialog.accept(prompts.shift() ?? ''); else await dialog.accept() })
try {
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
  assert.match(await page.title(), /Excel Report/)
  await page.locator('input[type=file][accept=".xlsx"]').setInputFiles(source)
  await page.locator('tbody tr').first().waitFor()
  assert.equal(await page.locator('tbody tr').count(), 5)
  await page.locator('input[type=date]').first().fill('2026-10-28')
  await page.locator('nav button').nth(1).click()
  prompts.push('Kiem chung')
  await page.locator('.toolbar button').click()
  prompts.push('Nhom chung')
  await page.getByRole('button', { name: '+ Nhóm' }).click()
  await page.locator('input[aria-label="Tên file nhóm"]').fill('NhomChung')
  prompts.push('Thanh Nga', 'Long Biên')
  await page.getByRole('button', { name: '+ Hãng' }).click()
  await page.getByRole('button', { name: '+ Hãng' }).click()
  assert.equal(await page.locator('.brand').count(), 2)
  prompts.push('Nhom rieng')
  await page.getByRole('button', { name: '+ Nhóm' }).click()
  await page.locator('input[aria-label="Tên file nhóm"]').nth(1).fill('HoangLong')
  prompts.push('HTX Hoàng Long')
  await page.getByRole('button', { name: '+ Hãng' }).nth(1).click()
  await page.locator('.group').first().locator('.brand').nth(1).locator('select').selectOption({ index: 1 })
  assert.equal(await page.locator('.group').nth(1).locator('.brand').count(), 2)
  await page.locator('.group').nth(1).locator('.brand').first().locator('select').selectOption({ index: 0 })
  await page.waitForTimeout(500)
  await page.reload({ waitUntil: 'networkidle' })
  await page.locator('nav button').nth(1).click()
  assert.equal(await page.locator('.group').count(), 2)
  assert.equal(await page.locator('.brand').count(), 3)
  await page.locator('nav button').first().click()
  await page.locator('input[type=file][accept=".xlsx"]').setInputFiles(source)
  await page.locator('tbody tr').first().waitFor()
  await page.locator('input[type=date]').first().fill('2026-10-28')
  assert.match(await page.locator('main').innerText(), /4 file/)
  const downloadPromise = page.waitForEvent('download')
  await page.locator('.primary').filter({ hasText: /ZIP/ }).click()
  const download = await downloadPromise
  mkdirSync('verification-output', { recursive: true })
  await download.saveAs('verification-output/browser-export.zip')
  assert.ok(existsSync('verification-output/browser-export.zip'))
  const zip = await JSZip.loadAsync(readFileSync('verification-output/browser-export.zip'))
  const xlsx = Object.values(zip.files).filter(f => f.name.endsWith('.xlsx'))
  assert.equal(xlsx.length, 4)
  const counts = []
  for (const file of xlsx) { const book = new ExcelJS.Workbook(); await book.xlsx.load(Uint8Array.from(await file.async('uint8array')).buffer); counts.push(book.worksheets[0].rowCount - 1) }
  assert.deepEqual(counts.sort((a,b)=>a-b), [4,25,34,63])
  await page.locator('.alert.good').filter({ hasText: /4 file/ }).waitFor()
  await page.screenshot({ path: 'verification-output/browser-dashboard.png', fullPage: true })
  console.log('E2E PASS: import, preview, week, categories, groups, brands, move, persistence, ZIP download')
  await page.getByRole('button', { name: 'Chọn thư mục cha' }).click()
  await page.waitForTimeout(1000)
  console.log('Directory picker result:', await page.locator('.alert.error').textContent().catch(() => 'no error'))
  await page.locator('nav button').nth(3).click()
  await page.locator('select').last().selectOption('strict')
  await page.locator('nav button').first().click()
  assert.equal(await page.locator('.primary').filter({ hasText: /ZIP/ }).isDisabled(), true)
  await page.locator('nav button').nth(3).click()
  await page.locator('select').last().selectOption('confirmed-skip')
  await page.locator('nav button').first().click()
  const skipDownloadPromise = page.waitForEvent('download')
  await page.locator('.primary').filter({ hasText: /ZIP/ }).click()
  const skipDownload = await skipDownloadPromise
  await skipDownload.saveAs('verification-output/browser-confirmed-skip.zip')
  const skipZip = await JSZip.loadAsync(readFileSync('verification-output/browser-confirmed-skip.zip'))
  assert.equal(Object.values(skipZip.files).filter(f => f.name.endsWith('.xlsx')).length, 3)
  await page.locator('nav button').nth(3).click()
  await page.locator('select').last().selectOption('flexible')
  console.log('E2E PASS: Strict disabled export; Confirmed Skip prompted and downloaded three files')
} finally { await browser.close() }
